print("=" * 60)
print("3. СРАВНЕНИЕ МОДЕЛЕЙ")
print("=" * 60)


# Функция для расчёта метрик качества модели
def calc_metrics(y_true, y_pred, model):
    """
    Вычисляет три метрики качества:
    1. R² (коэффициент детерминации) - доля объяснённой дисперсии
    2. MAPE (средняя ошибка аппроксимации) - средняя относительная ошибка в %
    3. RMSE (среднеквадратичная ошибка) - абсолютная ошибка
    """
    # R² = 1 - RSS/TSS, RSS - остаточная сумма квадратов, TSS - общая сумма квадратов
    r2 = model.rsquared

    # MAPE = (100%/n) * sum(|(y_i - ŷ_i)/y_i|)
    mape = np.mean(np.abs((y_true - y_pred) / y_true)) * 100

    # RMSE = sqrt(mean((y_i - ŷ_i)^2))
    rmse = np.sqrt(np.mean((y_true - y_pred) ** 2))

    return r2, mape, rmse


# Вычисляем метрики для всех трёх моделей
r2_lin, mape_lin, rmse_lin = calc_metrics(y, y_pred_lin, model_lin)
r2_quad, mape_quad, rmse_quad = calc_metrics(y, y_pred_quad, model_quad)
r2_log, mape_log, rmse_log = calc_metrics(y, y_pred_log, model_log)

# Создаём таблицу для наглядного сравнения
comp_df = pd.DataFrame({
    'Модель': ['Линейная', 'Квадратичная', 'Полулогарифмическая'],
    'R²': [f"{r2_lin:.3f}", f"{r2_quad:.3f}", f"{r2_log:.3f}"],
    'Средняя ошибка аппроксимации A, %': [f"{mape_lin:.1f}", f"{mape_quad:.1f}", f"{mape_log:.1f}"],
    'RMSE': [f"{rmse_lin:.2f}", f"{rmse_quad:.2f}", f"{rmse_log:.2f}"]
})
print(comp_df.to_string(index=False))

# Выбираем лучшую модель
# Создаём список кортежей: (название, R², MAPE, RMSE)
models_metrics = [
    ('Линейная', r2_lin, mape_lin, rmse_lin),
    ('Квадратичная', r2_quad, mape_quad, rmse_quad),
    ('Полулогарифмическая', r2_log, mape_log, rmse_log)
]

# Находим модель с максимальным R² (чем больше, тем лучше)
best_r2 = max(models_metrics, key=lambda x: x[1])

# Находим модель с минимальной ошибкой MAPE (чем меньше, тем лучше)
best_mape = min(models_metrics, key=lambda x: x[2])

print(f"\n   ВЫВОД: Наилучшей моделью является {best_r2[0]}.")
print(f"   Она имеет наибольший коэффициент детерминации (R² = {best_r2[1]:.3f})")
print(f"   и наименьшую среднюю ошибку аппроксимации (A = {best_mape[2]:.1f}%).\n")

# -----------------------------------------------------------------------------
# АНАЛИЗ ОСТАТКОВ
# -----------------------------------------------------------------------------
# Остатки e_i = y_i - ŷ_i показывают отклонения модели от данных
# Хорошая модель: остатки случайно разбросаны вокруг нуля без паттернов

fig, axes = plt.subplots(1, 3, figsize=(15, 5))
for i, (name, preds, color) in enumerate([('Линейная', y_pred_lin, 'red'),
                                          ('Квадратичная', y_pred_quad, 'green'),
                                          ('Полулогарифмическая', y_pred_log, 'blue')]):
    # Вычисляем остатки
    residuals = y - preds

    # Строим scatter plot: прогнозы vs остатки
    axes[i].scatter(preds, residuals, color=color, alpha=0.7, s=40)
    axes[i].axhline(0, color='black', linestyle='--', linewidth=1)  # Линия y=0
    axes[i].set_title(f'Остатки: {name}', fontsize=11)
    axes[i].set_xlabel('ŷ (прогноз)', fontsize=10)
    axes[i].set_ylabel('e = y - ŷ', fontsize=10)

plt.tight_layout()
