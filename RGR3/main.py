# -----------------------------------------------------------------------------
# 4.1 РАСЧЁТ ОСТАТКОВ И ДИСПЕРСИИ
# -----------------------------------------------------------------------------

# Вычисляем остатки: e_i = y_i - ŷ_i
residuals_lin = y - y_pred_lin

# RSS (Residual Sum of Squares) - остаточная сумма квадратов
# RSS = sum(e_i^2) = sum((y_i - ŷ_i)^2)
RSS = np.sum(residuals_lin ** 2)

# s² - несмещённая оценка дисперсии ошибок
# s² = RSS / (n - 2), где n-2 - степени свободы
# Вычитаем 2, так как оценили 2 параметра (a и b)
s2 = RSS / (n - 2)

# s - стандартное отклонение ошибок (стандартная ошибка регрессии)
s = np.sqrt(s2)

print(f"Оценки коэффициентов: â = {a_lin:.4f},  b̂ = {b_lin:.6f}")
print(f"Остаточная сумма квадратов (RSS) = {RSS:.2f}")
print(f"Несмещённая оценка дисперсии ошибки s² = RSS/(n-2) = {s2:.2f}")
print(f"Стандартное отклонение ошибки s = √s² = {s:.2f}\n")

# -----------------------------------------------------------------------------
# 4.2 ДОВЕРИТЕЛЬНЫЕ ИНТЕРВАЛЫ ДЛЯ КОЭФФИЦИЕНТОВ
# -----------------------------------------------------------------------------
# Доверительный интервал показывает диапазон, в котором с заданной вероятностью
# находится истинное значение параметра генеральной совокупности.
#
# Формула: β̂ ± t_(α/2; n-2) * SE(β̂)
# где SE - стандартная ошибка коэффициента, t - квантиль распределения Стьюдента

# Получаем 95% доверительные интервалы из модели
# conf_int() автоматически вычисляет стандартные ошибки и применяет t-распределение
conf_int = model_lin.conf_int(alpha=0.05)

print(f"95% Доверительный интервал для â: [{conf_int[0, 0]:.2f} ; {conf_int[0, 1]:.2f}]")
print(f"95% Доверительный интервал для b̂: [{conf_int[1, 0]:.6f} ; {conf_int[1, 1]:.6f}]")
print("Интерпретация: с вероятностью 95% истинный коэффициент лежит в этом интервале.\n")

# -----------------------------------------------------------------------------
# 4.3 ПРОВЕРКА ГИПОТЕЗЫ О ЗНАЧИМОСТИ КОЭФФИЦИЕНТА
# -----------------------------------------------------------------------------
# Проверяем, статистически ли значим коэффициент b (есть ли связь между x и y)
#
# Нулевая гипотеза H₀: b = 0 (связи нет, x не влияет на y)
# Альтернативная гипотеза H₁: b ≠ 0 (связь есть, x влияет на y)
#
# Используем t-тест Стьюдента:
# t_набл = b̂ / SE(b̂)
#
# Если |t_набл| > t_крит, отвергаем H₀ (коэффициент значим)

# Вычисляем t-статистику для коэффициента b
# model_lin.bse[1] - стандартная ошибка коэффициента b (SE(b̂))
t_stat = b_lin / model_lin.bse[1]

# Находим критическое значение t-распределения Стьюдента
# t.ppf(0.975, df) - это 97.5-й процентиль (для двустороннего теста с α=0.05)
# df = n - 2 - степени свободы
t_crit = stats.t.ppf(0.975, df=n - 2)

# p-value - вероятность получить такое или более экстремальное значение
# статистики при условии, что верна H₀
p_val = model_lin.pvalues[1]

print(f" Проверка гипотезы H₀: b = 0  против  H₁: b ≠ 0  (α = 0.05)")
print(f"   t_набл = b̂ / SE(b̂) = {t_stat:.4f}")
print(f"   t_крит (α=0.05, df={n - 2}) = {t_crit:.4f}")
print(f"   p-value = {p_val:.2e}")

# Делаем вывод о значимости
if abs(t_stat) > t_crit:
    print("   Вывод: |t_набл| > t_крит. Гипотеза H₀ отвергается.")
    print(
        "   Коэффициент при x статистически значим. Существует линейная зависимость между памятью и производительностью.")
else:
    print("   Вывод: Гипотеза H₀ не отвергается. Зависимость не значима.")

