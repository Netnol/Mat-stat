# x* = 105% от среднего значения x
x_star = 12377.995

# Вычисляем прогноз по каждой модели, подставляя x* в уравнения
y_star_lin = a_lin + b_lin * x_star
y_star_quad = a_quad + b_quad * x_star + c_quad * x_star ** 2
y_star_log = a_log + b_log * np.log(x_star)

print(f"Прогноз по линейной модели:          ŷ = {y_star_lin:.2f} усл. ед.")
print(f"Прогноз по квадратичной модели:      ŷ = {y_star_quad:.2f} усл. ед.")
print(f"Прогноз по полулогарифмической:      ŷ = {y_star_log:.2f} усл. ед.")
print(f"\n Основная модель для прогноза: {best_r2[0]} (наиболее адекватна данным).")
print(f" Интерпретация: Для вычислительной платформы с максимальным объёмом памяти {x_star:.0f} КБ")
print(f"   ожидаемая относительная производительность составляет примерно {y_star_quad:.0f} усл. ед.")
print(f"   Это согласуется с закономерностью: с ростом объёма памяти производительность увеличивается,")
print(f"   причём темпы роста ускоряются (квадратичная зависимость).")

