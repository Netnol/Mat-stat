# -----------------------------------------------------------------------------
# 2.1 ЛИНЕЙНАЯ МОДЕЛЬ: y = a + bx
# -----------------------------------------------------------------------------
# Метод наименьших квадратов (МНК) находит a и b, минимизирующие сумму
# квадратов отклонений: sum(y_i - (a + b*x_i))^2

# Создаём матрицу плана [1, x]
# Добавляем константу (столбец единиц) для оценки свободного члена a
X_lin = sm.add_constant(x)  # Теперь X_lin = [1, x]

# Строим модель Ordinary Least Squares (OLS) - метод наименьших квадратов
model_lin = sm.OLS(y, X_lin).fit()
# .fit() решает систему нормальных уравнений: β = (X^T X)^{-1} X^T y
# Возвращает объект с результатами: коэффициенты, ошибки, p-value и т.д.

# Извлекаем оценённые параметры
a_lin, b_lin = model_lin.params  # params[0] = a, params[1] = b

# Получаем прогнозные значения для всех наблюдений
y_pred_lin = model_lin.predict(X_lin)

print(f"  Линейная модель: y = {a_lin:.4f} + {b_lin:.6f} * x")

# -----------------------------------------------------------------------------
# 2.2 КВАДРАТИЧНАЯ МОДЕЛЬ: y = a + bx + cx^2
# -----------------------------------------------------------------------------
# МНК находит a, b, c минимизирующие sum(y_i - (a + b*x_i + c*x_i^2))^2

# Создаём матрицу плана: [1, x, x^2]
X_quad = sm.add_constant(np.column_stack((x, x ** 2)))

# Оцениваем параметры модели
model_quad = sm.OLS(y, X_quad).fit()

# Извлекаем параметры: a (константа), b (коэфф. при x), c (коэфф. при x^2)
a_quad, b_quad, c_quad = model_quad.params

# Прогнозные значения
y_pred_quad = model_quad.predict(X_quad)

print(f"  Квадратичная модель: y = {a_quad:.4f} + {b_quad:.6f} * x + {c_quad:.10f} * x^2")

# -----------------------------------------------------------------------------
# 2.3 ПОЛУЛОГАРИФМИЧЕСКАЯ МОДЕЛЬ: y = a + b*ln(x)
# -----------------------------------------------------------------------------
# Модель линейна относительно ln(x), поэтому:
# 1. Заменяем переменную: z = ln(x)
# 2. Строим линейную регрессию: y = a + bz

# Вычисляем натуральный логарифм от x
x_ln = np.log(x)

# Добавляем константу и строим модель
X_log = sm.add_constant(x_ln)
model_log = sm.OLS(y, X_log).fit()

# Параметры модели
a_log, b_log = model_log.params

# Прогнозы
y_pred_log = model_log.predict(X_log)

print(f"  Полулогарифмическая модель: y = {a_log:.4f} + {b_log:.4f} * ln(x)\n")

# -----------------------------------------------------------------------------
# ВИЗУАЛИЗАЦИЯ: Сравниваем все три модели на одном графике
# -----------------------------------------------------------------------------
# Сортируем x для плавного построения линий
x_sorted = np.sort(x)

plt.figure(figsize=(10, 6))
# Исходные данные
plt.scatter(x, y, label='Эмпирические данные', color='gray', alpha=0.6, s=50)

# Линейная модель (красная линия)
plt.plot(x_sorted, a_lin + b_lin * x_sorted,
         label=f'Линейная: y={a_lin:.1f}+{b_lin:.5f}x', color='red', linewidth=2)

# Квадратичная модель (зелёная линия)
plt.plot(x_sorted, a_quad + b_quad * x_sorted + c_quad * x_sorted ** 2,
         label='Квадратичная', color='green', linewidth=2)

# Полулогарифмическая модель (синяя линия)
plt.plot(x_sorted, a_log + b_log * np.log(x_sorted),
         label=f'Полулог: y={a_log:.1f}+{b_log:.2f}ln(x)', color='blue', linewidth=2)

plt.title('Сравнение регрессионных моделей', fontsize=14)
plt.xlabel('x (Объём памяти, КБ)', fontsize=12)
plt.ylabel('y (Производительность, усл. ед.)', fontsize=12)
plt.legend(fontsize=10)
plt.savefig('models_comparison.png', dpi=300, bbox_inches='tight')
plt.show()

