df = pd.read_csv('RGR3_A_3.csv')

# Извлекаем данные в numpy-массивы для удобства вычислений
x = df['x'].values  # Фактор: максимальный объём памяти (КБ)
y = df['y'].values  # Результат: производительность (усл. ед.)
n = len(x)  # Количество наблюдений (n = 60)

# Выводим информацию о данных
print(f"Источник данных: MASS::cpus (Performance of Computer CPUs)")
