import pandas as pd
import numpy as np
from scipy import stats
import warnings

def fmt_p(p):
    """Форматирует p-value: научная нотация, если < 0.0001"""
    return f"{p:.2e}" if p < 0.0001 else f"{p:.6f}"

warnings.filterwarnings('ignore')

# ---------------- ЗАГРУЗКА ДАННЫХ ----------------
df = pd.read_csv('RGR2_A-3_X1-X4.csv', sep=';')
n = len(df)
alpha = 0.05

X1 = df['X1'].values
X2 = df['X2'].values
X3 = df['X3'].values
X4 = df['X4'].values

print(f"Загружено данных: n = {n} наблюдений")
print(f"Уровень значимости: α = {alpha}\n")

# ==========================================================
# 4.2. Проверка гипотезы о равенстве мат. ожиданий (X1, X2)
# ==========================================================
print("="*60)
print("ЗАДАНИЕ 4.2: Сравнение средних двух независимых выборок (X1, X2)")
print("="*60)

print("Гипотезы:")
print("   H₀: μ₁ = μ₂ (математические ожидания равны)")
print("   H₁: μ₁ ≠ μ₂ (двусторонняя альтернатива)")
print(f"   Уровень значимости: α = {alpha}")
print("      Критерий: Двухвыборочный t-критерий Стьюдента с объединённой дисперсией.")
print("      Обоснование: выборки независимы, объём велик (n=102). Согласно методическим указаниям, отдельная проверка нормальности не требуется; t-критерий устойчив к умеренным отклонениям от нормального закона при больших n (ЦПТ).")
print("      Ошибка I рода: отвергнуть H₀, когда на самом деле μ₁ = μ₂. Вероятность: α = 5%.\n")

# Вычисление статистики
t_stat, p_val = stats.ttest_ind(X1, X2, equal_var=True)
df_t = n + n - 2
t_crit = stats.t.ppf(1 - alpha/2, df_t)
s_pooled = np.sqrt(((n-1)*np.var(X1, ddof=1) + (n-1)*np.var(X2, ddof=1)) / df_t)

print(f"Результаты:")
print(f"   x̄₁ = {np.mean(X1):.4f}, s₁ = {np.std(X1, ddof=1):.4f}")
print(f"   x̄₂ = {np.mean(X2):.4f}, s₂ = {np.std(X2, ddof=1):.4f}")
print(f"   Объединённое σ_p = {s_pooled:.4f}")
print(f"   t_набл = {t_stat:.4f}")
print(f"   df = {df_t}, t_крит(α/2={alpha/2}; df={df_t}) = ±{t_crit:.4f}")
print(f"   p-value = {fmt_p(p_val)}")

decision_42 = "ОТВЕРГАЕМ H₀" if abs(t_stat) > t_crit else "НЕТ ОСНОВАНИЙ ОТВЕРГНУТЬ H₀"
print(f"   Решение: {decision_42} (|t_набл| {'>' if abs(t_stat) > t_crit else '≤'} t_крит)")
print(f"   Вывод: На уровне значимости {alpha} имеются статистически значимые различия между средними значениями X1 и X2.")

# ==========================================================
# 4.3. Проверка гипотезы о параметре норм. распределения (X3)
# ==========================================================
print("\n" + "="*60)
print("ЗАДАНИЕ 4.3: Проверка гипотезы о мат. ожидании (X3)")
print("="*60)

mu0 = 63.27
print("Гипотезы:")
print("   H₀: μ = 63.27")
print("   H₁: μ ≠ 63.27 (двусторонняя альтернатива)")
print(f"   Уровень значимости: α = {alpha}")
print("      Критерий: Одновыборочный t-критерий Стьюдента.")
print("      Обоснование: дисперсия генеральной совокупности неизвестна. При n=102 t-критерий применим и устойчив; согласно методическим указаниям, дополнительная проверка нормальности не требуется.")
print("      Ошибка I рода: отвергнуть H₀, когда на самом деле μ = 63.27. Вероятность: α = 5%.\n")

t_stat3, p_val3 = stats.ttest_1samp(X3, mu0)
df_t3 = n - 1
t_crit3 = stats.t.ppf(1 - alpha/2, df_t3)

print(f"Результаты:")
print(f"   x̄₃ = {np.mean(X3):.4f}, s₃ = {np.std(X3, ddof=1):.4f}")
print(f"   t_набл = {t_stat3:.4f}")
print(f"   df = {df_t3}, t_крит(α/2={alpha/2}; df={df_t3}) = ±{t_crit3:.4f}")
print(f"   p-value = {fmt_p(p_val3)}")

decision_43 = "ОТВЕРГАЕМ H₀" if abs(t_stat3) > t_crit3 else "НЕТ ОСНОВАНИЙ ОТВЕРГНУТЬ H₀"
print(f"     Решение: {decision_43} (|t_набл| {'>' if abs(t_stat3) > t_crit3 else '≤'} t_крит)")
print(f"     Вывод: Выборочное среднее статистически значимо отличается от 63.27 мс.")

# ==========================================================
# 4.4. Непараметрический критерий для двух выборок (X1, X2)
# ==========================================================
print("\n" + "="*60)
print("ЗАДАНИЕ 4.4: Непараметрическое сравнение (X1, X2)")
print("="*60)

print("Гипотезы:")
print("   H₀: Распределения X1 и X2 идентичны (медианы равны)")
print("   H₁: Распределения различаются")
print(f"   Уровень значимости: α = {alpha}")
print("      Критерий: Критерий Манна–Уитни (U-критерий).")
print("      Обоснование: не требует предположения о нормальности и равенстве дисперсий.")
print("      Ошибка I рода: отвергнуть H₀, когда распределения на самом деле одинаковы. Вероятность: α = 5%.\n")

# Явно указываем двустороннюю альтернативу
u_stat, p_val_u = stats.mannwhitneyu(X1, X2, alternative='two-sided')

print(f"Результаты:")
print(f"   U_набл = {u_stat:.2f}")
print(f"   p-value = {fmt_p(p_val_u)}")

decision_44 = "ОТВЕРГАЕМ H₀" if p_val_u < alpha else "НЕТ ОСНОВАНИЙ ОТВЕРГНУТЬ H₀"
print(f"     Решение: {decision_44} (p-value {'<' if p_val_u < alpha else '≥'} α)")
print(f"     Вывод: Распределения X1 и X2 статистически значимо различаются.\n")

print("Сравнение с п. 4.2:")
print(f"   Параметрический критерий (t-Стьюдента): {decision_42}")
print(f"   Непараметрический критерий (Манна–Уитни): {decision_44}")
print("    Выводы совпадают. Это подтверждает устойчивость результата: различия между выборками носят систематический характер и не зависят от предположения о нормальности.")

# ==========================================================
# 4.5. Критерий согласия Пирсона χ² (столбец X4)
# ==========================================================
print("\n" + "="*60)
print("🔹 ЗАДАНИЕ 4.5: Критерий согласия χ² (X4 ~ Exp(λ=0.076))")
print("="*60)

lam = 0.076
print("Гипотезы:")
print(f"   H₀: X4 имеет показательное распределение с параметром λ = {lam}")
print(f"   H₁: X4 не имеет указанного распределения")
print(f"   Уровень значимости: α = {alpha}")
print("    Критерий: Критерий согласия Пирсона χ².")
print("    Ошибка I рода: отвергнуть H₀, когда данные на самом деле следуют Exp(λ). Вероятность: α = 5%.\n")

# 1. Формируем исходные интервалы равной ширины от 0 до max(X4)
k_init = 12  # начальное число интервалов
x_max = np.max(X4)
bins = np.linspace(0, x_max, k_init + 1)
bins[-1] = np.inf  # последний интервал до бесконечности

# 2. Функция CDF экспоненциального распределения
def exp_cdf(x, l): return 1 - np.exp(-l * x)

# 3. Теоретические вероятности и ожидаемые частоты
expected_probs = np.array([exp_cdf(bins[i+1], lam) - exp_cdf(bins[i], lam) for i in range(len(bins)-1)])
expected_freqs = expected_probs * n

# 4. Наблюдаемые частоты
observed_freqs, _ = np.histogram(X4, bins=bins)

# 5. Объединение интервалов с E_i < 5
obs_merged = []
exp_merged = []
bounds_merged = []
curr_o, curr_e, curr_left = 0, 0, bins[0]

for o, e, right in zip(observed_freqs, expected_freqs, bins[1:]):
    curr_o += o
    curr_e += e
    if curr_e >= 5:
        obs_merged.append(curr_o)
        exp_merged.append(curr_e)
        bounds_merged.append((curr_left, right))
        curr_o, curr_e, curr_left = 0, 0, right

# Если остался "хвост", добавляем к последнему интервалу
if curr_o > 0 and obs_merged:
    obs_merged[-1] += curr_o
    exp_merged[-1] += curr_e
    bounds_merged[-1] = (bounds_merged[-1][0], np.inf)
elif curr_o > 0:
    obs_merged.append(curr_o)
    exp_merged.append(curr_e)
    bounds_merged.append((curr_left, np.inf))

obs_merged = np.array(obs_merged)
exp_merged = np.array(exp_merged)
m = len(obs_merged)

# 6. Расчёт χ²
chi2_stat = np.sum((obs_merged - exp_merged)**2 / exp_merged)
df_chi2 = m - 1  # λ задан априори, не оценивался по выборке → df = m - 1
chi2_crit = stats.chi2.ppf(1 - alpha, df_chi2)
p_val_chi2 = 1 - stats.chi2.cdf(chi2_stat, df_chi2)

# 7. Вывод таблицы с точными границами и формульными обозначениями
print("Таблица интервалов (после объединения n·p_k ≥ 5):")
print(f"{'Интервал':<18} | {'n_k (набл.)':<11} | {'n·p_k (ожид.)':<13} | {'Вклад (n_k-n·p_k)²/n·p_k':<14}")
print("-" * 72)
for (a, b), o, e in zip(bounds_merged, obs_merged, exp_merged):
    b_str = "∞" if np.isinf(b) else f"{b:.2f}"
    contrib = (o - e)**2 / e
    print(f"[{a:.2f}; {b_str:<4})  | {o:<11} | {e:<13.2f} | {contrib:<14.4f}")

print(f"\n Результаты:")
print(f"   χ²_набл = {chi2_stat:.4f}")
print(f"   m = {m} интервалов, df = {df_chi2} (параметр λ задан заранее)")
print(f"   χ²_крит(α={alpha}; df={df_chi2}) = {chi2_crit:.4f}")
print(f"   p-value = {fmt_p(p_val_chi2)}")

decision_45 = "ОТВЕРГАЕМ H₀" if chi2_stat > chi2_crit else "НЕТ ОСНОВАНИЙ ОТВЕРГНУТЬ H₀"
print(f"   Решение: {decision_45} (χ²_набл {'>' if chi2_stat > chi2_crit else '≤'} χ²_крит)")
print(f"   Вывод: На уровне значимости {alpha} выборка X4 НЕ согласуется с показательным распределением Exp(λ={lam}).")

# ==========================================================
# 4.6. Итоговый вывод
# ==========================================================
print("\n" + "="*60)
print("ЗАДАНИЕ 4.6: ИТОГОВЫЙ ВЫВОД")
print("="*60)
summary = f"""
1. Пункт 4.2: Проверено равенство средних X1 и X2 (t-критерий Стьюдента). H₀ ОТВЕРГНУТА. Среднее X1 значимо больше среднего X2.
2. Пункт 4.3: Проверена гипотеза μ = 63.27 для X3 (t-критерий). H₀ ОТВЕРГНУТА. Фактическое среднее ~{np.mean(X3):.2f} мс статистически выше заданного.
3. Пункт 4.4: Непараметрическое сравнение X1 и X2 (Манна–Уитни). H₀ ОТВЕРГНУТА. Вывод совпадает с п. 4.2, что повышает надёжность результата.
4. Пункт 4.5: Проверка согласия X4 с Exp(λ=0.076) (χ² Пирсона). H₀ ОТВЕРГНУТА. Распределение данных существенно отличается от заданного экспоненциального закона.

Общий итог: Все проверяемые нулевые гипотезы были отвергнуты на уровне α=0.05. 
Различия между X1 и X2 носят систематический характер, параметр X3 не соответствует заданному значению, а модель Exp(λ=0.076) не описывает данные X4.
"""
print(summary)